void AAuraHUD::InitOverlay(APlayerController* PC, APlayerState* PS, UAbilitySystemComponent* ASC, UAttributeSet* AS)
{
	checkf(OverlayWidgetClass, TEXT("OverlayWidgetClass uninitialized, please fill out BP_AuraHUD"));
	checkf(OverlayWidgetControllerClass, TEXT("OverlayWidgetControllerClass uninitialized, please fill out BP_AuraHUD"));

	// Create the Overlay Widget and Widget Controller
	UUserWidget* Widget = CreateWidget<UUserWidget>(GetWorld(), OverlayWidgetClass);
	OverlayWidget = Cast<UAuraUserWidget>(Widget);
	
	const FWidgetControllerParams WCParams = FWidgetControllerParams(PC, PS, ASC, AS);
	UOverlayWidgetController* OverlayController = GetOverlayWidgetController(WCParams);

	OverlayWidget->SetWidgetController(OverlayController);
	OverlayController->BroadcastInitialValues();
	
	Widget->AddToViewport();
}
